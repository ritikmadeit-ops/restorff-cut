/**
 * The export gate: Restorff's Judge worker on the mastered render (README of restorff/workers/judge, §2):
 * ingest → analyze → captions → craft → findings. The Judge's work folder is put INSIDE the job folder
 * (RESTORFF_JUDGE_WORK), so nothing made from test media lands in the judge's git-ignored `work/` or the repo.
 *
 * Brief: the pipeline writes `brief/script.json` from the kept transcript (a talking head's approved copy is what it
 * says), with `offer: false` (not an ad: the R15 offer check is skipped by design, not passed). The caption band given
 * to OCR is where the pipeline actually put its captions.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { TimedWord } from "@restorffcut/timeline-ops";
import { JUDGE_DIR, PY } from "./paths.ts";
import { run } from "./util.ts";

export interface GateResult {
	gate: string;
	counts: { must: number; should: number; info: number };
	notRun: string[];
	findingsPath: string;
	judgeJobDir: string;
	steps: Record<string, number>;
	summary: string;
	exitCode: number;
}

const SENTENCE_END = /[.!?]$/;

/** Kept words → script.json (fictional-safe: it only holds what the video itself says). */
export function scriptFromWords(words: TimedWord[], deliver: { w: number; h: number }) {
	const sentences: string[] = [];
	let current: string[] = [];
	for (const w of words) {
		current.push(w.text);
		if (SENTENCE_END.test(w.text)) {
			sentences.push(current.join(" "));
			current = [];
		}
	}
	if (current.length) sentences.push(current.join(" "));
	const [hook = "", ...rest] = sentences;
	const cta = rest.length > 1 ? rest.slice(-1) : [];
	const hold = rest.length > 1 ? rest.slice(0, -1) : rest;
	return {
		brand: "(test input: talking head)",
		product: "(none)",
		source: "restorffcut pipeline: the kept transcript of the auto-cut (approved copy = what the speaker says)",
		notes: ["auto-generated by @restorffcut/pipeline; not an ad, so offer: false"],
		hooks: [{ n: 1, copy: hook, visuals: [] }],
		hold: { copy: hold },
		cta: { copy: cta },
		label_words: [],
		end_card: [],
		asr_aliases: {},
		deliver,
		offer: false,
	};
}

export async function gate(
	jobDir: string,
	video: string,
	opts: { quick?: boolean; band?: [number, number]; deliver?: { w: number; h: number } } = {},
): Promise<GateResult> {
	const judgeWork = join(jobDir, "judge");
	const briefDir = join(jobDir, "brief");
	mkdirSync(judgeWork, { recursive: true });
	mkdirSync(briefDir, { recursive: true });
	const cut = JSON.parse(readFileSync(join(jobDir, "cut.json"), "utf8")) as { keptWords: TimedWord[] };
	writeFileSync(
		join(briefDir, "script.json"),
		`${JSON.stringify(scriptFromWords(cut.keptWords, opts.deliver ?? { w: 1080, h: 1920 }), null, 1)}\n`,
	);
	const name = "gate";
	const env = { RESTORFF_JUDGE_WORK: judgeWork, PYTHONIOENCODING: "utf-8" };
	const steps: Record<string, number> = {};
	const judge = async (args: string[], allow: number[] = [0]) => {
		const r = await run(PY, ["judge.py", ...args], { cwd: JUDGE_DIR, env, echo: true });
		steps[args[0]] = r.ms;
		if (!allow.includes(r.code)) throw new Error(`judge.py ${args.join(" ")} failed (exit ${r.code}): ${r.stderr.slice(-800)}`);
		return r;
	};
	await judge(["ingest", name, "--edit", video, "--brief-dir", briefDir]);
	await judge(["analyze", name, ...(opts.quick ? ["--quick"] : [])]);
	await judge(["captions", name, ...(opts.band ? ["--band", String(opts.band[0]), String(opts.band[1])] : [])]);
	await judge(["craft", name]);
	const findings = await judge(["findings", name], [0, 2]);
	const judgeJobDir = join(judgeWork, name);
	const findingsPath = join(judgeJobDir, "findings.json");
	if (!existsSync(findingsPath)) throw new Error(`judge wrote no findings.json in ${judgeJobDir}`);
	copyFileSync(findingsPath, join(jobDir, "findings.json"));
	// findings@1: `findings` is keyed by the judged file ({"master.mp4": [finding, ...]}).
	const f = JSON.parse(readFileSync(findingsPath, "utf8")) as {
		gate?: string | { state?: string };
		not_run?: Array<string | { check?: string; why?: string }>;
		findings?: Record<string, Array<{ severity: string }>> | Array<{ severity: string }>;
	};
	const all = Array.isArray(f.findings) ? f.findings : Object.values(f.findings ?? {}).flat();
	const counts = { must: 0, should: 0, info: 0 };
	for (const x of all) {
		if (x.severity in counts) counts[x.severity as keyof typeof counts]++;
	}
	const gateState = typeof f.gate === "string" ? f.gate : (f.gate?.state ?? "?");
	return {
		gate: gateState,
		counts,
		notRun: (f.not_run ?? []).map((n) => (typeof n === "string" ? n : `${n.check ?? "?"}: ${n.why ?? ""}`)),
		findingsPath: join(jobDir, "findings.json"),
		judgeJobDir,
		steps,
		summary: findings.stdout.trim().split("\n").slice(0, 40).join("\n"),
		exitCode: findings.code,
	};
}
